"""`data/metadata.csv` — the one data file the repository commits (`CLAUDE.md` rule 4).

Schema is `docs/02` §4. This module owns reading it, writing it, and the two rules that
keep it trustworthy:

**Replacement, not appending.** `replace_session_rows` swaps out every row of one
session and leaves the others alone, so `tasks.py ingest` is idempotent. Appending would
double a session's weight in training on the second run, and because the duplicates are
legitimate rows of legitimate images, nothing downstream would flag it.

**No mixed provenance.** A `metadata.csv` holds synthetic sessions or real ones, never
both. Synthetic frames exist to test the pipeline (`tools/synth_capture.py`); if one
reached a training set, a number describing a renderer would end up in the TDR
presented as a measurement of a plate. The check is cheap and the failure it prevents is
not recoverable after the fact.

Rows are stored sorted by `(session_id, freq_hz, image_id)` so that re-ingesting a
session produces a minimal, readable diff.

**One row per raw image, accepted or not** — §4, literally. The `quality` column carries
the gate's verdict (`ok`, `blurred`, `partial`, `reject`), so the yield is visible in the
committed file itself rather than only in `data/ingest_report.json`, which is not
committed. A rejected row has an empty `split`: it is not part of any partition, it is
never loaded for training, and leaving it `unassigned` would make it look like a frame
the splitter had simply not reached yet.

The alternative — writing only accepted rows — makes `quality` constant and hides the
rejection rate from everyone reading the repository, which is precisely the number
`docs/02` §6 says is a reported result of the project.
"""

from __future__ import annotations

import csv
import re
from collections.abc import Iterable
from pathlib import Path
from typing import Any

#: docs/02 §4, in order.
METADATA_COLUMNS = (
    "image_id",
    "session_id",
    "freq_hz",
    "split",
    "material",
    "grain_mass_g",
    "distance_mm",
    "lighting",
    "dwell_s",
    "roi_mode",
    "quality",
    "notes",
)

SPLIT_UNASSIGNED = "unassigned"
SPLIT_VALUES = ("train", "val", "test")

#: A rejected image belongs to no partition at all. Distinct from `unassigned`, which
#: means "accepted, and `tasks.py split` has not run yet".
SPLIT_NONE = ""

#: docs/02 §4. `ok` is the only value that earns a split.
QUALITY_OK = "ok"
QUALITY_VALUES = ("ok", "blurred", "partial", "reject")


def is_accepted(row: dict[str, Any]) -> bool:
    return row.get("quality") == QUALITY_OK

SYNTHETIC_PREFIX = "SYNTH-"

#: A real session is a capture date and a run number: `YYYYMMDD-NN`.
REAL_SESSION_RE = re.compile(r"^\d{8}-\d{2}$")

#: A synthetic one is **the same id with a prefix**, not a parallel format. The prefix is
#: what makes it impossible to mistake for a measurement; the rest has to match, or the
#: dry run stops exercising the id parsing it exists to exercise. `SYNTH-01` would have
#: been a shorter id that never once put `YYYYMMDD-NN` through the code that reads it.
SYNTHETIC_SESSION_RE = re.compile(r"^SYNTH-\d{8}-\d{2}$")


class MetadataError(ValueError):
    """`metadata.csv` is malformed, or the operation would corrupt it."""


class MixedProvenanceError(MetadataError):
    """Synthetic and real sessions would end up in the same dataset."""


def is_synthetic(session_id: str) -> bool:
    return session_id.startswith(SYNTHETIC_PREFIX)


def validate_session_id(session_id: str) -> str:
    """`YYYYMMDD-NN` for a capture, `SYNTH-YYYYMMDD-NN` for a generated one. Nothing else.

    An unrecognised id is fatal rather than tolerated: `docs/02` §2 makes `session_id`
    the grouping key for the split, so an id that does not parse is an image that
    cannot be safely assigned to train, val or test.
    """
    if REAL_SESSION_RE.match(session_id) or SYNTHETIC_SESSION_RE.match(session_id):
        return session_id
    raise MetadataError(
        f"session_id {session_id!r} is neither YYYYMMDD-NN (a capture) nor "
        f"SYNTH-YYYYMMDD-NN (generated by tools/synth_capture.py)"
    )


def session_date(session_id: str) -> str:
    """The `YYYYMMDD` part of either form. Raises on an id that does not parse."""
    validate_session_id(session_id)
    return session_id.split("-")[1] if is_synthetic(session_id) else session_id.split("-")[0]


def read_metadata(path: Path | str) -> list[dict[str, Any]]:
    p = Path(path)
    if not p.exists():
        return []
    with p.open(newline="", encoding="utf-8") as fh:
        reader = csv.DictReader(fh)
        missing = [c for c in METADATA_COLUMNS if c not in (reader.fieldnames or [])]
        if missing:
            raise MetadataError(f"{p}: missing column(s) {', '.join(missing)}")
        return list(reader)


def write_metadata(rows: Iterable[dict[str, Any]], path: Path | str) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    with p.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(METADATA_COLUMNS), extrasaction="ignore")
        w.writeheader()
        w.writerows(sort_rows(rows))
    return p


def sort_rows(rows: Iterable[dict[str, Any]]) -> list[dict[str, Any]]:
    return sorted(rows, key=lambda r: (r["session_id"], int(r["freq_hz"]), r["image_id"]))


def replace_session_rows(
    existing: list[dict[str, Any]], session_id: str, new_rows: list[dict[str, Any]]
) -> list[dict[str, Any]]:
    """Every row of `session_id` swapped for `new_rows`; all other sessions untouched."""
    kept = [r for r in existing if r["session_id"] != session_id]
    return sort_rows(kept + new_rows)


def check_provenance(existing: list[dict[str, Any]], session_id: str) -> None:
    """Refuse to put a synthetic session and a real one in the same dataset."""
    incoming_synthetic = is_synthetic(session_id)
    conflicting = sorted(
        {
            r["session_id"]
            for r in existing
            if r["session_id"] != session_id and is_synthetic(r["session_id"]) != incoming_synthetic
        }
    )
    if not conflicting:
        return

    kind = "synthetic" if incoming_synthetic else "real"
    other = "real" if incoming_synthetic else "synthetic"
    raise MixedProvenanceError(
        f"refusing to ingest {kind} session {session_id!r}: metadata.csv already holds "
        f"{other} session(s) {', '.join(conflicting)}. SYNTH-* sessions exist only to "
        f"exercise the pipeline and must never be trained on alongside captures. Move or "
        f"delete data/metadata.csv (and data/processed/) before switching provenance."
    )


def split_counts(rows: Iterable[dict[str, Any]]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for r in rows:
        counts[r["split"]] = counts.get(r["split"], 0) + 1
    return counts


def sessions_by_split(rows: Iterable[dict[str, Any]]) -> dict[str, set[str]]:
    out: dict[str, set[str]] = {}
    for r in rows:
        out.setdefault(r["split"], set()).add(r["session_id"])
    return out
